// AP.t('level_n', {n: 5}) -> "Level 5"
AP.t = function (key, vars) {
  const d = AP.STR[AP.lang] || AP.STR.en;
  let s = d[key] !== undefined ? d[key] : (AP.STR.en[key] !== undefined ? AP.STR.en[key] : key);
  if (vars && typeof s === 'string') s = s.replace(/\{(\w+)\}/g, (m, k) => vars[k] !== undefined ? vars[k] : m);
  return s;
};
AP.addStrings = function (tbl) { for (const lang in tbl) { AP.STR[lang] = AP.STR[lang] || {}; Object.assign(AP.STR[lang], tbl[lang]); } };
